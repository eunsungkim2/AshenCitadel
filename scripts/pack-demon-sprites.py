"""Build the browser sprite bundle from the project's source PNGs."""
import base64
import io
import json
from pathlib import Path

from PIL import Image

root = Path(__file__).resolve().parents[1] / "assets"
demons = root / "demons"
roster = json.loads((demons / "rank-1-6.json").read_text(encoding="utf-8"))
seventh = ["wrath", "sloth", "pride", "greed", "lust", "gluttony", "envy", "oblivion", "morga"]
roster.extend({"star": 7, "identity": i, "file": f"{name}.png"} for i, name in enumerate(seventh))
sprites = {}
for unit in roster:
    path = demons / unit["file"]
    data = path.read_bytes()
    if unit["star"] == 7:
        with Image.open(path) as image:
            image.thumbnail((192, 192), Image.Resampling.NEAREST)
            output = io.BytesIO()
            image.save(output, format="PNG", optimize=True)
            data = output.getvalue()
    sprites[f'{unit["star"]}:{unit["identity"]}'] = base64.b64encode(data).decode("ascii")

if len(sprites) != 87:
    raise ValueError(f"Expected 87 demon sprites, packed {len(sprites)}")
(root / "demon-sprites.js").write_text(
    "// Generated by scripts/pack-demon-sprites.py.\nconst bundledDemonSprites = "
    + json.dumps(sprites, indent=2) + ";\n",
    encoding="utf-8",
)
